function hasEffectiveDate() {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(legalConfig.effectiveDate)) return false;
  const date = new Date(`${legalConfig.effectiveDate}T00:00:00+08:00`);
  if (!Number.isFinite(date.getTime())) return false;
  const chinaDate = new Date(date.getTime() + 8 * 60 * 60 * 1000).toISOString().slice(0, 10);
  return chinaDate === legalConfig.effectiveDate && date.getTime() <= Date.now();
}

function isReady() {
  return legalConfig.configured === true
    && hasEffectiveDate()
    && ['operatorName', 'contact', 'effectiveDate', 'privacyVersion', 'agreementVersion']
      .every((key) => typeof legalConfig[key] === 'string' && legalConfig[key].trim())
    && ['privacySections', 'agreementSections'].every((key) =>
      Array.isArray(legalConfig[key]) && legalConfig[key].length > 0
      && legalConfig[key].every((section) => section && typeof section.heading === 'string'
        && section.heading.trim() && typeof section.text === 'string' && section.text.trim()));
}

