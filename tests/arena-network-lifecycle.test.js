const test = require('node:test');
const assert = require('node:assert/strict');
const {loadArenaPage, makeArenaFrames} = require('./helpers/arena-view-fixture');
const api = require('../utils/api-client');
const privacy = require('../utils/privacy-consent');
const tick = () => new Promise((resolve) => setImmediate(resolve));
function harness(t) {
  const page = loadArenaPage();
  t.mock.method(privacy, 'canEnter', () => true);
  t.mock.method(api, 'getToken', () => 'current-account');
  Object.assign(page, {sessionId: '9', generation: 1, active: true});
  page.connectArenaRealtime = () => {}; page.startArenaPolling = () => {};
  t.after(() => page.stopArena());
  return page;
}
test('联机页面在下一帧响应拖动、短距离回拨和松手，无需新快照', (t) => {
  const page = harness(t), sent = [];
  const [frame] = makeArenaFrames(1);
  page.snapshot = frame;
  page.socketOpen = true;
  page.socket = {send({data}) {sent.push(JSON.parse(data).data);}, close() {}};
  page.draw();
  const start = page.data.players[0].px;
  page.onRunTouchStart({touches: [{x: 100, y: 100}]});
  page.onRunTouchMove({touches: [{x: 150, y: 100}]});
  page.drawMotionFrame(Date.now() + 16);
  const moving = page.data.players[0].px;
  assert.ok(moving > start);
  page.onRunTouchMove({touches: [{x: 140, y: 100}]});
  assert.ok(sent.at(-1).dx < 0);
  page.drawMotionFrame(Date.now() + 32);
  assert.ok(page.data.players[0].px < moving);
  const stopped = page.data.players[0].px;
  page.onRunTouchCancel();
  assert.deepEqual(sent.at(-1), {dx: 0, dy: 0});
  page.drawMotionFrame(Date.now() + 48);
  assert.equal(page.data.players[0].px, stopped);
  assert.equal(page.snapshot, frame);
});
test('前台恢复不等旧HTTP快照，旧请求结束不能释放新请求的锁', async (t) => {
  const page = harness(t), reads = [];
  t.mock.method(api, 'get', () => new Promise((resolve, reject) => reads.push({resolve, reject})));
  const accepted = []; page.acceptState = (state) => accepted.push(state);
  const old = page.fetchArenaState();
  page.stopArena(); page.onShow();
  assert.equal(reads.length, 2, '恢复立即读取新快照');
  reads[0].reject(new Error('旧连接超时')); await old;
  assert.doesNotMatch(page.data.connectionText, /网络中断/);
  await page.fetchArenaState(); assert.equal(reads.length, 2, '旧请求不能解锁新请求');
  reads[1].resolve({stateVersion: 2}); await tick();
  assert.deepEqual(accepted, [{stateVersion: 2}]);
});
test('移动请求跨后台隔离，迟到失败不覆盖新状态、不解锁新移动队列', async (t) => {
  const page = harness(t), moves = [];
  page.fetchArenaState = () => {};
  t.mock.method(api, 'post', (_path, direction) => new Promise((resolve, reject) => moves.push({direction, resolve, reject})));
  page.direction = {dx: 1, dy: 0}; page.sendDirection();
  page.stopArena(); page.onShow();
  page.direction = {dx: -1, dy: 0}; page.sendDirection();
  assert.equal(moves.length, 2);
  moves[0].reject(new Error('旧移动请求超时')); await tick();
  assert.equal(page.data.error, '');
  page.direction = {dx: 0, dy: 1}; page.sendDirection();
  assert.equal(moves.length, 2, '新移动仍在请求中，不被旧finally提前释放');
  moves[1].resolve({}); await tick();
  assert.equal(moves.length, 3); assert.equal(moves[2].direction.dy, 1);
  moves[2].resolve({}); await tick();
});
